export const DEFAULT_SIZE: ButtonSize = "medium";

export function getTheme(value: string): Theme {
  return THEMES.find((t) => t.value === value) ?? THEMES[0];
}

export function getButtonSize(value: ButtonSize) {
  return BUTTON_SIZES.find((s) => s.value === value) ?? BUTTON_SIZES[1];
}
